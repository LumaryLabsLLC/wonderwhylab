export function projector(W: number) {
  const H = (W * (LAT_TOP - LAT_BOTTOM)) / 360;
  return {
    W,
    H,
    x: (lon: number) => ((lon + 180) / 360) * W,
    y: (lat: number) => ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H,
    lon: (x: number) => (x / W) * 360 - 180,
    lat: (y: number) => LAT_TOP - (y / H) * (LAT_TOP - LAT_BOTTOM),
  };
}

function inPoly([px, py]: LL, poly: LL[]) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Which continent (if any) covers this longitude/latitude? */
export function continentAt(p: LL): ContinentId | null {
  return CONTINENT_IDS.find((id) => CONTINENTS[id].some((poly) => inPoly(p, poly))) ?? null;
}

/** Which ocean does this point of water belong to? */
export function oceanAt([lon, lat]: LL): OceanId {
  if (lat < -58) return 'southern';
  if (lat > 72) return 'arctic';
  let best: OceanId = 'pacific';
  let d = Infinity;
  for (const [id, [cl, ct]] of OCEAN_CENTRES) {
    const dl = Math.min(Math.abs(lon - cl), 360 - Math.abs(lon - cl));
    const dd = dl * dl + (lat - ct) * (lat - ct);
    if (dd < d) {
      d = dd;
      best = id;
    }
  }
  return best;
}

export function polyPath(poly: LL[], pr: ReturnType<typeof projector>) {
  return `M${poly.map(([lo, la]) => `${pr.x(lo).toFixed(1)},${pr.y(la).toFixed(1)}`).join(' L')} Z`;
}

/** A small world map for questions. `highlight` picks out one continent; `ring` circles a spot. */
export function WorldMini({ highlight, ring, label, colours = true }: { highlight?: ContinentId; ring?: LL; label: string; colours?: boolean }) {
  const pr = projector(360);
  return (
    <svg viewBox={`-3 -8 ${pr.W + 6} ${pr.H + 11}`} role="img" aria-label={label}>
      <rect x={0} y={0} width={pr.W} height={pr.H} rx={6} fill={SEA} stroke={C.ink} strokeWidth={2} />
      {CONTINENT_IDS.map((id) =>
        CONTINENTS[id].map((poly, i) => (
          <path
            key={`${id}${i}`}
            d={polyPath(poly, pr)}
            fill={highlight ? (id === highlight ? C.orange : '#e8e2d4') : colours ? CONTINENT_FILL[id] : '#e8e2d4'}
            stroke={C.ink}
            strokeWidth={id === highlight ? 1.6 : 0.8}
            strokeLinejoin="round"
          />
        )),
      )}
      {ring && (
        <g>
          <circle cx={pr.x(ring[0])} cy={pr.y(ring[1])} r={17} fill="none" stroke={C.yellow} strokeWidth={6} />
          <circle cx={pr.x(ring[0])} cy={pr.y(ring[1])} r={17} fill="none" stroke={C.ink} strokeWidth={2} />
        </g>
      )}
    </svg>
  );
}
